function gateMachine(): Machine {
  const states: MState[] = [
    {
      id: "turn",
      label: "Fin de tour",
      sub: "turn.complete, fil principal",
      kind: "initial",
      lead: "Le mod a rendu le résultat de <code>next(e)</code>. Un tour de sous-agent s'arrête ici, sans journal. Les outils du tour s'ajoutent aux faits ; un tour interrompu marque afterInterrupt.",
    },
    ...GATE_CHECKS.flatMap((c): MState[] => [
      c.sub === undefined
        ? { id: c.id, label: c.label, kind: "check", lead: c.lead }
        : { id: c.id, label: c.label, sub: c.sub, kind: "check", lead: c.lead },
      {
        id: `skip-${c.id}`,
        label: "Journal : skip",
        sub: c.skip.replace(/^\w+ : /, ""),
        kind: "outcome",
        lead: "Rien ne se passe. La raison, le score et les signaux sont journalisés ; <code>hindsight status</code> les compte par raison.",
        where: "gate_decisions.decision = 'skip'",
      },
    ]),
    {
      id: "debrief",
      label: "Journal : debrief",
      sub: "puis le fork",
      kind: "outcome",
      lead: "La ligne de journal, puis <code>debrief start</code>, le fork et <code>debrief record</code>.",
      where: "gate_decisions.decision = 'debrief'",
    },
  ];

  const transitions: MTransition[] = [
    {
      id: "g-0",
      from: "turn",
      to: "c1",
      event: "faits du tour ajoutés",
      by: "code",
      desc: "addToolUses sur les outils du dernier tour, puis writeState, avant tout saut.",
      src: "src/mod/gate.ts · afterTurn",
    },
    ...GATE_CHECKS.flatMap((c, i) => {
      const after = GATE_CHECKS[i + 1]?.id ?? "debrief";

      const out: MTransition[] = [
        {
          id: `g-${c.id}-skip`,
          from: c.id,
          to: `skip-${c.id}`,
          event: c.skip,
          by: c.skipBy,
          desc: c.skipDesc,
          src: c.src,
        },
        {
          id: `g-${c.id}-next`,
          from: c.id,
          to: after,
          event: c.next,
          by: c.id === "c9" ? "model" : "code",
          desc: "",
          src: c.src,
        },
      ];

      return out;
    }),
  ];

  return {
    id: "m-gate",
    title: "Portail",
    tag: "src/domain/gate.ts · src/mod/gate.ts · gate_decisions",
    lead: "Un arbre de décision, pas une machine : à chaque fin de tour du fil principal, les sauts directs dans l'ordre du code, puis le score, puis le classifieur. Chaque sortie est une ligne du journal. <code>/hindsight debrief</code> entre directement au verrou, sans saut ni classifieur.",
    store:
      "une ligne <code>gate_decisions</code> par sortie : decision (skip | debrief | forced), reason, score, signals_json",
    initial: "turn",
    direction: "RIGHT",
    facts: [
      ["Poids 1", "human_marker · tool_refused · after_interrupt · rule_file_edit"],
      ["Poids 0,5", "many_edits (≥ 3) · tool_errors (≥ 2) · git_commit"],
      ["Refroidissement", `cooldownMs ${G.cooldownMs} × min(Debriefs de la session, ${G.cooldownMaxSteps})`],
    ],
    states,
    transitions,
    src: "src/domain/gate.ts · gateSkip, gateSignals · src/mod/gate.ts · afterTurn, classifyThenDebrief · docs/adr/0005",
  };
}

